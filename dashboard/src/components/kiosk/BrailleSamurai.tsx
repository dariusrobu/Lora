function popcount(b: number): number {
  let c = 0
  while (b) { c += b & 1; b >>= 1 }
  return c
}

const LUT = new Float32Array(256)
for (let i = 0; i < 256; i++) LUT[i] = popcount(i) / 8

function brailleBrightness(c: string): number {
  const code = c.charCodeAt(0)
  if (code < 0x2800 || code > 0x28FF) return 0
  return LUT[code & 0xFF]
}

function stripRepeatingEdges(grid: string[][]): void {
  const h = grid.length
  const w = grid[0].length
  if (w === 0) return

  const blank: boolean[][] = Array.from({ length: h }, () => new Array(w).fill(false))

  for (let y = 0; y < h; y++) {
    const row = grid[y]
    let x = 0
    while (x <= w - 9) {
      const a = row[x], b = row[x + 1], c = row[x + 2]
      let reps = 1
      for (let xx = x + 3; xx <= w - 3; xx += 3) {
        if (row[xx] === a && row[xx + 1] === b && row[xx + 2] === c) reps++
        else break
      }
      if (reps >= 3) {
        for (let r = 0; r < reps; r++) {
          blank[y][x + r * 3] = true
          blank[y][x + r * 3 + 1] = true
          blank[y][x + r * 3 + 2] = true
        }
        x += reps * 3
      } else {
        x++
      }
    }
  }

  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      if (blank[y][x]) grid[y][x] = "\u2800"
    }
  }
}

function parseArt(raw: string): { grid: string[][]; w: number; h: number } {
  const lines = raw.split("\n")
  const maxW = Math.max(...lines.map(l => [...l].length))
  const grid = lines.map(l => {
    const row = [...l]
    while (row.length < maxW) row.push("\u2800")
    return row
  })
  stripRepeatingEdges(grid)
  return { grid, w: maxW, h: lines.length }
}

